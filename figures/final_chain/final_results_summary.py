"""
Final EngressNet results table (2026-10-07): the final configuration (T2 amplitude maps + 10 px energy tiles + noise-parameter
lr x10) against the separately trained deterministic U-Net (det-MSE) and bilinear interpolation.

  Perfect model, test year 2021, ocean cells (truth = FOSI / MESACLIP 0.1 deg; 4 training windows averaged):
    RMSE / MAE of the best estimate (ensemble mean; det-MSE prediction; bilinear), CRPS (= MAE for single-valued estimates),
    corrected spread-skill (evaluation/corrected_calibration; 1 = calibrated)
  Observations (ICESat-2 pass-cell means, 2018-2022, from observations/data/alongtrack_eval/):
    PIOMAS input (scoreboard.csv) and pooled independent inputs PIOMAS + CS2SMOS + TOPAZ4-ML (input_comparison_scores.csv)
Writes figures/final_figures/final_results_table.csv and .md.
"""
import glob
import os

import numpy as np
import pandas as pd

V6 = "/glade/work/skygale/projects/SeaIceDownscaling"
OUT = f"{V6}/figures/final_figures/final_results_table"
# 2026-10-18: EngressNet (final) = 2026-10-07 configuration + EMA; det-MSE = matched det-MSE + EMA (seed 0)
PERFECT = {("FOSI", "EngressNet (final)"): "FOSI_final_ema", ("FOSI", "det-MSE"): "FOSI_detmse_ema",
           ("MESACLIP", "EngressNet (final)"): "MESA_final_ema", ("MESACLIP", "det-MSE"): "MESA_detmse_ema"}


def perfect_rows():
    rows = []
    for (ds, model), batch in PERFECT.items():
        acc = {"rmse": [], "mae": [], "brmse": [], "bmae": []}
        for f in sorted(glob.glob(f"{V6}/results/{batch}/*/eval_data/fields.npz")):
            z = np.load(f)
            T, P, Bl = z["Y_test_phys"][:, 0], z["Y_pred_phys"][:, 0], z["Y_base_phys"][:, 0]
            ocean = np.broadcast_to(z["mask_test"][:, 0] <= 0.5, T.shape) if z["mask_test"].shape[0] == T.shape[0] else \
                np.broadcast_to(z["mask_test"][0, 0] <= 0.5, T.shape)
            e, eb = (P - T)[ocean], (Bl - T)[ocean]
            acc["rmse"].append(np.sqrt(np.mean(e ** 2))); acc["mae"].append(np.mean(np.abs(e)))
            acc["brmse"].append(np.sqrt(np.mean(eb ** 2))); acc["bmae"].append(np.mean(np.abs(eb)))
        if not acc["rmse"]:
            print("missing", batch); continue
        r = {"test": f"perfect model, {ds} 2021", "estimate": model, "windows": len(acc["rmse"]),
             "RMSE": np.mean(acc["rmse"]), "MAE": np.mean(acc["mae"])}
        c = f"{V6}/evaluation/corrected_calibration/{batch}.csv"
        if model == "det-MSE":
            r["CRPS"] = r["MAE"]
        elif os.path.exists(c):
            d = pd.read_csv(c)
            d = d[d.run != "POOLED"] if (d.run == "POOLED").any() else d
            r["CRPS"], r["spread-skill"] = d["CRPS (ocean)"].mean(), d["Spread-skill ratio"].mean()
        rows.append(r)
        if model == "det-MSE":  # bilinear once per dataset (same truth and coarse input)
            rows.append({"test": f"perfect model, {ds} 2021", "estimate": "bilinear", "windows": len(acc["rmse"]),
                         "RMSE": np.mean(acc["brmse"]), "MAE": np.mean(acc["bmae"]), "CRPS": np.mean(acc["bmae"])})
    return rows


def obs_rows():
    rows = []
    s = pd.read_csv(f"{V6}/observations/data/alongtrack_eval/scoreboard.csv")
    s = s[(s.reference == "mean") & (s.subset == "all")].set_index("estimate")
    for est, lab in (("EngressNet (final)", "EngressNet (final)"), ("det-MSE", "det-MSE"), ("bilinear", "bilinear")):
        if est in s.index:
            x = s.loc[est]
            rows.append({"test": "ICESat-2 pass-cell mean, PIOMAS input, 2018-22", "estimate": lab, "RMSE": x["RMSE of mean"],
                         "MAE": x["MAE of mean"], "bias": x["bias (est − IS2)"], "r": x["r"], "CRPS": x["CRPS"],
                         "spread/error (+obs noise)": x["spread/error + obs noise"],
                         "within-cell var / IS2": x["subgrid std ratio (median)"], "53-160 km var / IS2": x["PSD ratio 53-160 km"]})
    ic = pd.read_csv(f"{V6}/observations/data/alongtrack_eval/input_comparison_scores.csv")
    for region in ("whole domain", "north of 66°N"):
        q = ic[(ic["reference | region"] == f"mean | {region}") & ic.estimate.str.startswith("EngressNet (final) | pooled independent")]
        for _, x in q.iterrows():
            rows.append({"test": f"ICESat-2 pass-cell mean, pooled inputs (PIOMAS+CS2SMOS+TOPAZ4-ML), {region}",
                         "estimate": "EngressNet (final)", "RMSE": x["RMSE of mean"], "bias": x["bias (est − IS2)"], "r": x["r"],
                         "CRPS": x["CRPS"], "spread/error (+obs noise)": x["spread/error + obs noise"],
                         "within-cell var / IS2": x["subgrid std ratio"]})
    return rows


def main():
    t = pd.DataFrame(perfect_rows() + obs_rows()).set_index(["test", "estimate"]).round(3)
    t.to_csv(f"{OUT}.csv")
    with open(f"{OUT}.md", "w") as f:
        f.write("# Final EngressNet results (generated by figures/final_chain/final_results_summary.py)\n\n")
        r = t.reset_index().astype(object).where(t.reset_index().notna(), "")
        f.write("| " + " | ".join(r.columns) + " |\n|" + "---|" * len(r.columns) + "\n")
        for _, row in r.iterrows():
            f.write("| " + " | ".join(str(v) for v in row) + " |\n")
    pd.set_option("display.width", 250); pd.set_option("display.max_columns", 20)
    print(t.to_string())
    print(f"\nwrote {OUT}.csv / .md")


if __name__ == "__main__":
    main()
